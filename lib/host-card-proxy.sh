# Proxy DNS por card: *. {slug}.olie.localhost → portas do host-card.
# Problema: N cards no jarvis não podem partilhar devframe.olie.localhost.
# .localhost já resolve para loopback; Caddy em :80 roteia pelo Host.
# Sourced by lib/host-card.sh / hooks.

workvm_host_card_proxy_dir() {
    printf '%s/proxy\n' "$(workvm_host_card_root)"
}

workvm_host_card_dns_slug() {
    # DOP-1183 → dop-1183 (label DNS)
    workvm_host_card_normalize_code "$1"
}

workvm_host_card_dns_urls() {
    local slug="$1"
    printf 'api_dns=http://api.%s.olie.localhost\n' "$slug"
    printf 'front_dns=http://devframe.%s.olie.localhost\n' "$slug"
}

workvm_host_card_proxy_write_caddyfile() {
    local proxy_dir caddy
    proxy_dir="$(workvm_host_card_proxy_dir)"
    caddy="${proxy_dir}/Caddyfile"
    mkdir -p "$proxy_dir"

    {
        printf '# Generated by workvm-host-card — do not edit by hand.\n'
        printf '{\n\tauto_https off\n\thttp_port %s\n}\n\n' \
            "${WORKVM_HOST_CARD_PROXY_PORT:-80}"
        local meta
        while IFS= read -r meta; do
            [ -n "$meta" ] || continue
            python3 - "$meta" <<'PY'
import json, sys
m = json.load(open(sys.argv[1], encoding="utf-8"))
slug = m.get("dns_slug") or ""
api = m.get("port_base")
front = (api + 1) if api is not None else None
if not slug or api is None:
    raise SystemExit(0)
print(f"http://api.{slug}.olie.localhost {{")
print(f"\treverse_proxy 127.0.0.1:{api}")
print("}")
print(f"http://devframe.{slug}.olie.localhost {{")
print(f"\treverse_proxy 127.0.0.1:{front}")
print("}")
print()
PY
        done < <(find "$(workvm_host_card_root)" -mindepth 3 -maxdepth 3 -name meta.json -print 2>/dev/null)
    } >"$caddy"

    # Always have a reachable stub so Caddy validates empty fleets.
    if ! grep -q 'reverse_proxy' "$caddy"; then
        printf 'http://host-card.olie.localhost {\n\trespond "no host-cards" 200\n}\n' >>"$caddy"
    fi
    printf '%s\n' "$caddy"
}

workvm_host_card_proxy_ensure() {
    local proxy_dir caddy port
    proxy_dir="$(workvm_host_card_proxy_dir)"
    port="${WORKVM_HOST_CARD_PROXY_PORT:-80}"
    caddy="$(workvm_host_card_proxy_write_caddyfile)"

    mkdir -p "$proxy_dir"
    cat >"${proxy_dir}/compose.yaml" <<EOF
# Proxy compartilhado dos host-cards (Caddy :${port}).
services:
  caddy:
    image: caddy:2-alpine
    container_name: workvm-host-card-proxy
    network_mode: host
    restart: unless-stopped
    volumes:
      - ${caddy}:/etc/caddy/Caddyfile:ro
EOF

    # Já rodando: só reload do Caddyfile (force-recreate colide no nome fixo).
    if docker ps --format '{{.Names}}' 2>/dev/null | grep -qx workvm-host-card-proxy; then
        workvm_host_card_log "proxy reload (Caddy :${port}, container já up)"
        docker exec workvm-host-card-proxy caddy reload --config /etc/caddy/Caddyfile 2>/dev/null \
            || workvm_host_card_log "caddy reload falhou — Caddyfile em ${caddy}"
        return 0
    fi

    workvm_host_card_log "proxy up (Caddy :${port})"
    (
        cd "$proxy_dir"
        docker compose up -d
    ) || {
        workvm_host_card_log "proxy falhou na :${port} — tente WORKVM_HOST_CARD_PROXY_PORT=8080"
        return 1
    }
    docker exec workvm-host-card-proxy caddy reload --config /etc/caddy/Caddyfile 2>/dev/null || true
}

workvm_host_card_proxy_reload() {
    workvm_host_card_proxy_write_caddyfile >/dev/null
    if docker ps --format '{{.Names}}' 2>/dev/null | grep -qx workvm-host-card-proxy; then
        docker exec workvm-host-card-proxy caddy reload --config /etc/caddy/Caddyfile 2>/dev/null \
            || workvm_host_card_proxy_ensure
    else
        # Only start proxy if at least one card exists
        if find "$(workvm_host_card_root)" -mindepth 3 -maxdepth 3 -name meta.json 2>/dev/null | grep -q .; then
            workvm_host_card_proxy_ensure
        fi
    fi
}
